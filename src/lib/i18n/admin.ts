export type Locale = "en" | "ru";

export function translator(locale: Locale) {
  return (key: MessageKey): string => (locale === "ru" ? (ru[key] ?? en[key]) : en[key]);
}

/** Plain object of translated strings to pass to client components. */
export function labelsFor(locale: Locale, keys: MessageKey[]): Record<MessageKey, string> {
  const t = translator(locale);
  return Object.fromEntries(keys.map((k) => [k, t(k)])) as Record<MessageKey, string>;
}

/** All strings whose key starts with one of the prefixes (for client components). */
export function labelsByPrefix(locale: Locale, prefixes: string[]): Record<MessageKey, string> {
  return labelsFor(
    locale,
    (Object.keys(en) as MessageKey[]).filter((k) => prefixes.some((p) => k.startsWith(p))),
  );
}
